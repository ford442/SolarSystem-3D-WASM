#!/usr/bin/env node
/**
 * Scan Application.cpp for EMSCRIPTEN_KEEPALIVE exports and emit TypeScript
 * fragments for SolarSystem.d.ts (SolarSystemCwrap overloads) and wasmBridge stubs.
 *
 * Usage: node scripts/generate-wasm-exports.mjs [--check]
 *   --check  Exit 1 if generated output would differ from committed files.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const applicationCpp = join(root, 'src/Application.cpp');
const dtsPath = join(root, 'web/src/SolarSystem.d.ts');
const bridgePath = join(root, 'web/src/wasmBridge.generated.ts');

const EXPORT_RE = /EMSCRIPTEN_KEEPALIVE\s+([\w\s*]+?)\s+(\w+)\s*\(([^)]*)\)/g;

/** Map C types to cwrap arg/return types. */
function mapCType(cType) {
    const t = cType.replace(/\s+/g, ' ').trim();
    if (t === 'void') return { tsReturn: 'void', cwrapReturn: 'null' };
    if (t === 'int' || t === 'float' || t === 'double' || t === 'bool') {
        return { tsReturn: 'number', cwrapReturn: 'number' };
    }
    if (t.endsWith('*')) return { tsReturn: 'number', cwrapReturn: 'number' };
    return { tsReturn: 'number', cwrapReturn: 'number' };
}

function parseParams(paramStr) {
    if (!paramStr.trim()) return [];
    return paramStr.split(',').map((p) => {
        const parts = p.trim().split(/\s+/);
        const cType = parts.slice(0, -1).join(' ') || parts[0];
        return mapCType(cType);
    });
}

function parseExports(source) {
    const exports = [];
    let match;
    while ((match = EXPORT_RE.exec(source)) !== null) {
        const [, returnType, name, params] = match;
        const ret = mapCType(returnType);
        const args = parseParams(params);
        exports.push({ name, ret, args });
    }
    return exports;
}

function generateCwrapOverload({ name, ret, args }) {
    const argTypes = args.map(() => "'number'").join(', ');
    const argTypesTuple = argTypes ? `[${argTypes}]` : '[]';
    return `  (
    ident: '${name}',
    returnType: ${ret.cwrapReturn === 'null' ? 'null' : `'${ret.cwrapReturn}'`},
    argTypes: ${argTypesTuple},
  ): (...args: number[]) => ${ret.cwrapReturn === 'null' ? 'void' : 'number'};`;
}

function generateBridgeStub({ name, ret, args }) {
    const argList = args.length ? `...args: number[]` : '';
    const call = args.length ? `(...args)` : `()`;
    return `        ${name[0].toLowerCase()}${name.slice(1)}: cwrap('${name}', ${ret.cwrapReturn === 'null' ? 'null' : `'${ret.cwrapReturn}'`}, [${args.map(() => "'number'").join(', ')}])${ret.cwrapReturn === 'null' ? '' : ' as () => number'},`;
}

function main() {
    const source = readFileSync(applicationCpp, 'utf8');
    const exports = parseExports(source);
    if (exports.length === 0) {
        console.error('No EMSCRIPTEN_KEEPALIVE exports found in', applicationCpp);
        process.exit(1);
    }

    const cwrapBlock = exports.map(generateCwrapOverload).join('\n');
    const bridgeBlock = exports.map(generateBridgeStub).join('\n');

    const generatedBridge = `// AUTO-GENERATED by scripts/generate-wasm-exports.mjs — do not edit.
// Stubs for manual merge into createSolarSystemRuntime(); regenerate after C++ export changes.

export const GENERATED_CWRAP_STUBS = \`
${bridgeBlock}
\`;

export const EXPORT_COUNT = ${exports.length};
`;

    const markerStart = '  // BEGIN GENERATED CWARP OVERLOADS';
    const markerEnd = '  // END GENERATED CWARP OVERLOADS';
    let dts = readFileSync(dtsPath, 'utf8');

    const generatedSection = `${markerStart}\n${cwrapBlock}\n  ${markerEnd}`;

    if (dts.includes(markerStart)) {
        dts = dts.replace(
            new RegExp(`${markerStart}[\\s\\S]*?${markerEnd}`),
            generatedSection,
        );
    } else {
        dts = dts.replace(
            /export interface SolarSystemCwrap \{/,
            `export interface SolarSystemCwrap {\n${generatedSection}`,
        );
    }

    // Drop stale hand-maintained overloads that may follow the generated block.
    dts = dts.replace(
        new RegExp(`(${markerEnd})\\s*\\([\\s\\S]*?\\n\\}`),
        '$1\n}',
    );

    const check = process.argv.includes('--check');

    if (check) {
        let existingBridgeContent = '';
        try {
            existingBridgeContent = readFileSync(bridgePath, 'utf8');
        } catch {
            existingBridgeContent = '';
        }
        const dtsChanged = readFileSync(dtsPath, 'utf8') !== dts;
        const bridgeChanged = existingBridgeContent !== generatedBridge;
        if (dtsChanged || bridgeChanged) {
            console.error('Generated wasm export bindings are out of date. Run: node scripts/generate-wasm-exports.mjs');
            process.exit(1);
        }
        console.log(`OK: ${exports.length} exports in sync`);
        return;
    }

    writeFileSync(dtsPath, dts);
    writeFileSync(bridgePath, generatedBridge);
    console.log(`Generated ${exports.length} export bindings → ${dtsPath}, ${bridgePath}`);
}

main();
