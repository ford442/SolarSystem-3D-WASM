#!/usr/bin/env node
/**
 * Write resource/shaders/common/texture_units.glsl from the SOLARSYSTEM_TEXTURE_UNITS
 * X-list in src/gfx/TextureUnits.h, so C++ and GLSL name the same unit numbers.
 *
 * Usage: node scripts/generate-texture-units.mjs [--check]
 *   --check  Exit 1 if the committed .glsl differs from what the header generates.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const headerPath = join(root, 'src/gfx/TextureUnits.h');
const glslPath = join(root, 'resource/shaders/common/texture_units.glsl');

const header = readFileSync(headerPath, 'utf8');
const listStart = header.indexOf('#define SOLARSYSTEM_TEXTURE_UNITS(X)');
if (listStart < 0) {
  console.error(`${headerPath}: SOLARSYSTEM_TEXTURE_UNITS(X) not found`);
  process.exit(1);
}
// The X-list is the macro's continuation lines.
const list = [];
for (const line of header.slice(listStart).split('\n').slice(1)) {
  const match = line.match(/^\s*X\((\w+),\s*(\d+),\s*(TU_\w+)\)/);
  if (match) {
    list.push({ name: match[1], value: Number(match[2]), glsl: match[3] });
  }
  if (!line.trimEnd().endsWith('\\')) {
    break;
  }
}
if (list.length === 0) {
  console.error(`${headerPath}: no X(Name, value, TU_NAME) entries`);
  process.exit(1);
}

const width = Math.max(...list.map((unit) => unit.glsl.length));
const lines = [
  '// Generated by scripts/generate-texture-units.mjs from src/gfx/TextureUnits.h. Do not edit.',
  '// Name a sampler\'s unit with `layout(binding = TU_...) uniform sampler2D name;`; ShaderSource',
  '// strips the qualifier (GLSL ES 3.00 has none) and Shader assigns the unit at link.',
  ...list.map((unit) => `#define ${unit.glsl.padEnd(width)} ${unit.value}`),
  '',
];
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(glslPath, 'utf8');
  } catch {
    // Missing counts as stale.
  }
  if (current !== output) {
    console.error(`${glslPath} is stale; run: node scripts/generate-texture-units.mjs`);
    process.exit(1);
  }
  console.log('texture_units.glsl is up to date');
} else {
  writeFileSync(glslPath, output);
  console.log(`wrote ${glslPath} (${list.length} units)`);
}
